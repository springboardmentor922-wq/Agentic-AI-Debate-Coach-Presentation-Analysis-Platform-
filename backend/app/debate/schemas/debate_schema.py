"""
Debate Processing Schemas

Purpose:
    Defines the request and response models for the complete
    debate processing workflow.

Responsibilities:
    - Standardize the final debate analysis response.
    - Aggregate outputs from Speech and AI modules.
    - Provide a single response contract for the frontend.

Supported Input Methods:
    - Live Speech Recording
    - Audio Upload
    - Video Upload

Note:
    This schema belongs to the Debate Module and acts as the
    contract between the backend and frontend.
"""

from pydantic import BaseModel, Field

from app.ai.schemas.argument_analysis_schema import (
    ArgumentAnalysisResponse,
)
from app.ai.schemas.fallacy_detection_schema import (
    FallacyDetectionResponse,
)
from app.ai.schemas.milestone3_schema import (
    AIDebateOpponentResponse, CoachingResponse, CounterargumentResponse,
    LearningPathResponse, PerformanceScore, RecommendationResponse,
    ObservabilityMetadata,
)


class DebateTranscription(BaseModel):
    """
    Speech transcription generated from the uploaded
    audio/video or live recording.
    """

    transcript: str = Field(
        ...,
        description="Speech transcript generated by Whisper."
    )


class SpeechMetrics(BaseModel):
    recording_id: int | None = None
    gridfs_id: str | None = None
    audio_duration_seconds: float | None = 0.0
    speech_pace_wpm: float | None = 0.0
    filler_words_count: int | None = 0
    filler_words_details: dict | str | None = None
    confidence_score: float | None = 0.0
    clarity_score: float | None = 0.0
    audience_engagement_score: float | None = 0.0
    prosody_pitch_variance: float | None = 0.0
    energy_variance: float | None = 0.0
    pause_count: int | None = 0
    overall_presentation_score: float | None = 0.0
    processing_status: str | None = None


class DebateAnalysisData(BaseModel):
    """
    Complete debate analysis generated for one debate turn.
    """

    session_id: int

    transcript: DebateTranscription

    argument_analysis: ArgumentAnalysisResponse

    logical_fallacy_analysis: FallacyDetectionResponse

    counterargument: CounterargumentResponse | None = None
    ai_debate_opponent: AIDebateOpponentResponse | None = None
    performance: PerformanceScore | None = None
    coaching: CoachingResponse | None = None
    recommendations: RecommendationResponse | None = None
    learning_path: LearningPathResponse | None = None
    progress_updated: bool | None = None
    observability: ObservabilityMetadata | None = None
    speech_metrics: SpeechMetrics | None = None


class DebateAnalysisResponse(BaseModel):
    """
    Final response returned after complete debate processing.
    """

    success: bool

    message: str

    data: DebateAnalysisData
